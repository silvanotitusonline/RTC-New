    fun getSampleDashboard(): PublicReportDashboard {
        val reports = getSampleReports()
        val open = reports.count { it.status == PublicReportStatus.SUBMITTED || it.status == PublicReportStatus.ACKNOWLEDGED }.toLong()
        val inProgress = reports.count { it.status == PublicReportStatus.IN_PROGRESS }.toLong()
        val resolved = reports.count { it.status == PublicReportStatus.COMPLETED || it.status == PublicReportStatus.CLOSED }.toLong()
        val total = reports.size.toLong()
        return PublicReportDashboard(
            openReports = open,
            inProgressReports = inProgress,
            resolvedReports = resolved,
            verifiedReports = total,
            activeReports = open + inProgress,
            unresolvedReports = open + inProgress,
        )
    }

